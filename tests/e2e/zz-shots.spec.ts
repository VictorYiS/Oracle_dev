import { test } from "@playwright/test";
import { cross, newGame, startDay, walkTo, cameraOnHero } from "./helpers";
test("shots", async ({ page }, info) => {
  test.setTimeout(120_000);
  const p = info.project.name;
  await newGame(page, 42);
  await startDay(page);
  await page.getByTestId("speed-pause").click();
  await page.keyboard.press("e");
  for (let i = 0; i < 60 && !(await page.getByTestId("case").isVisible()); i++)
    await page.evaluate(() => window.oracle!.advance(5));
  await page.screenshot({ path: info.outputPath(`${p}-desk.png`) });
  await page.getByTestId("paper-2").click();
  await page.waitForTimeout(200);
  await page.screenshot({ path: info.outputPath(`${p}-paper.png`) });
  await page.getByTestId("paper-close").click();
  await page.getByTestId("adopt").click();
  await page.keyboard.press("Escape");
  await page.getByTestId("pending-toggle").click();
  await page.waitForTimeout(200);
  await page.screenshot({ path: info.outputPath(`${p}-tray.png`) });
  await page.getByTestId("pending-toggle").click();
  await walkTo(page, 2900);
  await cross(page, "passage.stairs");
  await walkTo(page, 2220);
  await cameraOnHero(page);
  await page.screenshot({ path: info.outputPath(`${p}-riverbank.png`) });
  await walkTo(page, 1500);
  await cross(page, "passage.bridge");
  await walkTo(page, 1255);
  await cameraOnHero(page);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: info.outputPath(`${p}-farbank.png`) });
  await walkTo(page, 2220);
  await cross(page, "passage.door_17b");
  await page.waitForTimeout(500);
  await page.screenshot({ path: info.outputPath(`${p}-room.png`) });
  await cross(page, "passage.door_17b");
  await walkTo(page, 2600);
  await cameraOnHero(page);
  await page.screenshot({ path: info.outputPath(`${p}-alley.png`) });
  await cross(page, "passage.alley");
  await page.waitForTimeout(400);
  await page.screenshot({ path: info.outputPath(`${p}-substation.png`) });
});
