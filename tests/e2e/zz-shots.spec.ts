import { test } from "@playwright/test";
import { cross, goToFarBank, newGame, settled, startDay, walkTo, cameraOnHero } from "./helpers";
test("shots", async ({ page }, info) => {
  test.setTimeout(120_000);
  const dir = "tests/.tmp-scratch/";
  const p = info.project.name;
  await newGame(page, 42);
  await startDay(page);
  await page.getByTestId("speed-pause").click();
  await page.keyboard.press("e");
  for (let i = 0; i < 60 && !(await page.getByTestId("case").isVisible()); i++)
    await page.evaluate(() => window.oracle!.advance(5));
  await page.screenshot({ path: `${dir}${p}-desk.png` });
  await page.getByTestId("paper-2").click();
  await page.waitForTimeout(200);
  await page.screenshot({ path: `${dir}${p}-paper.png` });
  await page.getByTestId("paper-close").click();
  await page.getByTestId("adopt").click();
  await page.keyboard.press("Escape");
  await page.getByTestId("pending-toggle").click();
  await page.waitForTimeout(200);
  await page.screenshot({ path: `${dir}${p}-tray.png` });
  await page.getByTestId("pending-toggle").click();
  await goToFarBank(page);
  await walkTo(page, 1255);
  await cameraOnHero(page);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: `${dir}${p}-farbank.png` });
  await walkTo(page, 2220);
  await cross(page, "passage.door_17b");
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${dir}${p}-room.png` });
  await cross(page, "passage.door_17b");
  await walkTo(page, 2600);
  await cameraOnHero(page);
  await page.keyboard.press("w");
  await settled(page);
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${dir}${p}-alley.png` });
  await page.keyboard.press("Escape");
  await settled(page);
  await page.keyboard.press("w");
  await settled(page);
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${dir}${p}-sky.png` });
});
